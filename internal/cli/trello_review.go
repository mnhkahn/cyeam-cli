package cli

import (
	"context"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"time"

	"github.com/google/uuid"
	"github.com/mnhkahn/cyeam-cli/internal/trello"
	"github.com/spf13/cobra"
)

func newTrelloReviewCommand() *cobra.Command {
	var text, textFile, image, audio, reviewID string
	var grade string
	var provisional bool
	var retryUncertain, hasErrors bool
	cmd := &cobra.Command{
		Use:   "review <card-id>",
		Short: "Publish a text, image, or audio homework review to the original card",
		Long:  "Publish one homework review using protocol v1. Choose exactly one of --text, --text-file, --image, --audio. Reuse --review-id with identical input after a failure; a new ID creates a new history entry. State is saved under ~/.cyeam/trello-reviews/. Use --grade 100|优|良|中|差 to save 打分结果 at the top of the card description and in review history; add --provisional for a tentative grade. Grade 100 means fully correct and sets --has-errors=false; other grades do not determine --has-errors automatically.",
		Example: `  cyeam trello card review <card-id> --text-file review.txt --grade 良 --has-errors=true
  cyeam trello card review <card-id> --text-file review.txt --grade 优 --provisional
  cyeam trello card review <card-id> --image review.png --grade 优 --has-errors=false`,
		Args: cobra.ExactArgs(1),
		RunE: func(cmd *cobra.Command, args []string) error {
			if (cmd.Flags().Changed("grade") && !trello.ValidGrade(grade)) || (provisional && grade == "") {
				return fmt.Errorf("--grade must be 100, 优, 良, 中 or 差; --provisional requires --grade")
			}
			if grade == "100" && (provisional || (cmd.Flags().Changed("has-errors") && hasErrors)) {
				return fmt.Errorf("--grade 100 means fully correct; do not combine it with --provisional or --has-errors=true")
			}
			count := 0
			for _, flag := range []string{"text", "text-file", "image", "audio"} {
				if cmd.Flags().Changed(flag) {
					count++
				}
			}
			if count != 1 {
				return fmt.Errorf("choose exactly one of --text, --text-file, --image, --audio")
			}
			if retryUncertain && !cmd.Flags().Changed("review-id") {
				return fmt.Errorf("--retry-uncertain requires the original --review-id")
			}
			kind, file := "text", ""
			switch {
			case cmd.Flags().Changed("text-file"):
				data, err := os.ReadFile(textFile)
				if err != nil {
					return err
				}
				text = string(data)
			case cmd.Flags().Changed("image"):
				kind, file = "image", image
			case cmd.Flags().Changed("audio"):
				kind, file = "audio", audio
			}
			if reviewID == "" {
				if cmd.Flags().Changed("review-id") {
					return fmt.Errorf("--review-id cannot be empty")
				}
				reviewID = uuid.NewString()
			}
			// Canonical UUIDs make filenames safe and ensure the same ID has one state file.
			id, err := uuid.Parse(reviewID)
			if err != nil {
				return fmt.Errorf("--review-id must be a UUID: %w", err)
			}
			reviewID = id.String()
			home, err := os.UserHomeDir()
			if err != nil {
				return err
			}
			statePath := filepath.Join(home, ".cyeam", "trello-reviews", reviewID+".json")
			fmt.Fprintf(cmd.ErrOrStderr(), "review_id: %s\nstate_file: %s\n", reviewID, statePath)
			client, err := getTrelloClient()
			if err != nil {
				return err
			}
			ctx, cancel := context.WithTimeout(cmd.Context(), 2*time.Minute)
			defer cancel()
			var outcome *bool
			if cmd.Flags().Changed("has-errors") {
				outcome = &hasErrors
			}
			result, err := client.PublishReview(ctx, trello.ReviewOptions{CardID: args[0], ReviewID: reviewID, Type: kind, Text: text, File: file, StatePath: statePath, RetryUncertain: retryUncertain, HasErrors: outcome, Grade: grade, Provisional: provisional})
			if err != nil {
				return err
			}
			data, err := json.Marshal(result)
			if err != nil {
				return err
			}
			return writeTrelloJSON(cmd, data)
		},
	}
	cmd.Flags().StringVar(&text, "text", "", "plain text review")
	cmd.Flags().StringVar(&textFile, "text-file", "", "UTF-8 file containing a plain text review")
	cmd.Flags().StringVar(&image, "image", "", "one local jpg/jpeg/png/webp/gif file")
	cmd.Flags().StringVar(&audio, "audio", "", "one local m4a/mp3/wav/aac/ogg/opus/amr/3gp file (up to 50 MiB)")
	cmd.Flags().StringVar(&reviewID, "review-id", "", "UUID for this submission; reuse it on retry (generated by default)")
	cmd.Flags().BoolVar(&hasErrors, "has-errors", false, "explicit outcome: true moves to 待改错; false passes and preserves 已改错 (omit to publish only)")
	cmd.Flags().StringVar(&grade, "grade", "", "grade 100|优|良|中|差; 100 means fully correct, writes 打分结果 and marks the review passed")
	cmd.Flags().BoolVar(&provisional, "provisional", false, "mark grade as 暂评; requires --grade")
	cmd.Flags().BoolVar(&retryUncertain, "retry-uncertain", false, "permit another POST after reconciliation finds no match; may create duplicates")
	return cmd
}
